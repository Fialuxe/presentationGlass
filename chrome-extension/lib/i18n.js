  const FALLBACK = "en";
  const lang = (globalThis.navigator?.language || FALLBACK).split("-")[0].toLowerCase();
  const table = MESSAGES[lang] || MESSAGES[FALLBACK];

  function t(key, ...args) {
    const text = table[key] ?? MESSAGES[FALLBACK][key] ?? key;
    return text.replace(/\{(\d+)\}/g, (match, i) => (i < args.length ? String(args[i]) : match));
  }

  /** Fills every element with data-i18n (text) or data-i18n-placeholder (placeholder). */
  function translatePage(root = document) {
    root.documentElement.lang = MESSAGES[lang] ? lang : FALLBACK;
    for (const el of root.querySelectorAll("[data-i18n]")) {
      // Keep child elements (such as an <input> inside a <label>): replace only the first text.
      const textNode = [...el.childNodes].find((n) => n.nodeType === Node.TEXT_NODE);
      const text = t(el.dataset.i18n);
      if (textNode) textNode.textContent = `${text} `;
      else el.prepend(document.createTextNode(text));
    }
    for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    }
  }

  globalThis.PresentationGlass = globalThis.PresentationGlass || {};
  globalThis.PresentationGlass.i18n = { t, translatePage, lang, languages: Object.keys(MESSAGES) };
